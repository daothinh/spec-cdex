import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, "..");
const pluginsDir = path.join(repoRoot, "plugins");
const catalogPath = path.join(pluginsDir, "catalog.json");
const outputPath = path.join(repoRoot, "docs", "plugin-inventory.md");

async function main() {
  const catalog = await readJson(catalogPath);
  const pluginEntries = await collectPluginEntries(catalog);
  const summary = buildSummary(catalog, pluginEntries);
  const markdown = renderMarkdown(summary, pluginEntries);

  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, markdown, "utf8");

  console.log(
    `Wrote ${path.relative(repoRoot, outputPath)} with ${pluginEntries.length} plugins and ${summary.totalSkills} skills.`
  );
}

async function collectPluginEntries(catalog) {
  const catalogByName = new Map(catalog.plugins.map((plugin) => [plugin.name, plugin]));
  const directories = (await fs.readdir(pluginsDir, { withFileTypes: true }))
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort((left, right) => left.localeCompare(right));

  const entries = [];

  for (const name of directories) {
    const baseDir = path.join(pluginsDir, name);
    const catalogEntry = catalogByName.get(name);
    const skills = await collectSkillNames(path.join(baseDir, "skills"));
    const commands = await countFiles(path.join(baseDir, "commands"));
    const agents = await countFiles(path.join(baseDir, "agents"));
    const hooks = (await exists(path.join(baseDir, "hooks", "hooks.json"))) ? 1 : 0;

    entries.push({
      name,
      category: catalogEntry?.category ?? "Untracked",
      sourceKind: catalogEntry?.sourceKind ?? "untracked",
      codexStatus: catalogEntry?.codexStatus ?? "untracked",
      skills,
      commands,
      agents,
      hooks
    });
  }

  return entries;
}

function buildSummary(catalog, pluginEntries) {
  const summary = {
    totalPlugins: pluginEntries.length,
    totalSkills: pluginEntries.reduce((sum, entry) => sum + entry.skills.length, 0),
    totalCommands: pluginEntries.reduce((sum, entry) => sum + entry.commands, 0),
    totalAgents: pluginEntries.reduce((sum, entry) => sum + entry.agents, 0),
    totalHooks: pluginEntries.reduce((sum, entry) => sum + entry.hooks, 0),
    available: 0,
    blocked: 0,
    byCategory: new Map(),
    bySourceKind: new Map()
  };

  for (const plugin of catalog.plugins) {
    if (plugin.codexStatus === "available") {
      summary.available += 1;
    } else if (plugin.codexStatus === "blocked") {
      summary.blocked += 1;
    }

    summary.byCategory.set(plugin.category, (summary.byCategory.get(plugin.category) ?? 0) + 1);
    summary.bySourceKind.set(plugin.sourceKind, (summary.bySourceKind.get(plugin.sourceKind) ?? 0) + 1);
  }

  return summary;
}

function renderMarkdown(summary, pluginEntries) {
  const lines = [
    "# Plugin Inventory",
    "",
    "Generated by `node scripts/generate-plugin-inventory.mjs` from `plugins/catalog.json` and the root `plugins/` directory.",
    "",
    "## Summary",
    "",
    `- Total plugins: ${summary.totalPlugins}`,
    `- Codex marketplace available: ${summary.available}`,
    `- Codex marketplace blocked: ${summary.blocked}`,
    `- Total skills: ${summary.totalSkills}`,
    `- Total commands: ${summary.totalCommands}`,
    `- Total agents: ${summary.totalAgents}`,
    `- Total hooks: ${summary.totalHooks}`,
    "",
    "## Category Breakdown",
    "",
    "| Category | Count |",
    "| --- | ---: |",
    ...mapToRows(summary.byCategory),
    "",
    "## Source Breakdown",
    "",
    "| Source Kind | Count |",
    "| --- | ---: |",
    ...mapToRows(summary.bySourceKind),
    "",
    "## Plugin Catalog",
    "",
    "| Plugin | Category | Source | Codex | Skills | Commands | Agents | Hooks |",
    "| --- | --- | --- | --- | ---: | ---: | ---: | ---: |",
    ...pluginEntries.map(
      (entry) =>
        `| \`${entry.name}\` | ${entry.category} | ${entry.sourceKind} | ${entry.codexStatus} | ${entry.skills.length} | ${entry.commands} | ${entry.agents} | ${entry.hooks} |`
    ),
    "",
    "## Skills By Plugin",
    ""
  ];

  for (const entry of pluginEntries) {
    lines.push(`### ${entry.name}`);
    lines.push("");

    if (entry.skills.length === 0) {
      lines.push("- No `SKILL.md` files detected.");
    } else {
      for (const skill of entry.skills) {
        lines.push(`- \`${skill}\``);
      }
    }

    lines.push("");
  }

  return `${lines.join("\n")}\n`;
}

function mapToRows(map) {
  return [...map.entries()]
    .sort((left, right) => left[0].localeCompare(right[0]))
    .map(([key, value]) => `| ${key} | ${value} |`);
}

async function collectSkillNames(skillsDir) {
  if (!(await exists(skillsDir))) {
    return [];
  }

  const skillNames = [];
  const queue = [skillsDir];

  while (queue.length > 0) {
    const currentDir = queue.shift();
    const entries = await fs.readdir(currentDir, { withFileTypes: true });

    for (const entry of entries) {
      const fullPath = path.join(currentDir, entry.name);

      if (entry.isDirectory()) {
        queue.push(fullPath);
        continue;
      }

      if (entry.isFile() && entry.name === "SKILL.md") {
        skillNames.push(path.basename(path.dirname(fullPath)));
      }
    }
  }

  return [...new Set(skillNames)].sort((left, right) => left.localeCompare(right));
}

async function countFiles(dir) {
  if (!(await exists(dir))) {
    return 0;
  }

  let total = 0;
  const queue = [dir];

  while (queue.length > 0) {
    const currentDir = queue.shift();
    const entries = await fs.readdir(currentDir, { withFileTypes: true });

    for (const entry of entries) {
      const fullPath = path.join(currentDir, entry.name);
      if (entry.isDirectory()) {
        queue.push(fullPath);
      } else if (entry.isFile()) {
        total += 1;
      }
    }
  }

  return total;
}

async function exists(targetPath) {
  try {
    await fs.access(targetPath);
    return true;
  } catch {
    return false;
  }
}

async function readJson(targetPath) {
  return JSON.parse(await fs.readFile(targetPath, "utf8"));
}

await main();
